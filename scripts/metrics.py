#!/usr/bin/env python3
"""Fills in the retro's numbers from the review files, so nobody has to.

  python3 metrics.py [project dir]      a table: build, lane, rounds, first-round counts, last-round counts
  python3 metrics.py . --index          also writes reviews INDEX.md next to the reviews it found

It looks for review files under work/**/reviews/ and reviews/ and reads each one's verdict line:
  **Critical: 0 · Major: 3 · Minor: 9 · Nit: 2**
File names are read as <LANE><round>.md (SA2.md) or <build>-<LANE><round>.md (K5-SA3.md).
"""
import os, re, sys
from collections import defaultdict

VERDICT = re.compile(r'Critical:?\s*\**\s*(\d+).{0,12}?Major:?\s*\**\s*(\d+)(?:.{0,12}?Minor:?\s*\**\s*(\d+))?', re.I)
NAME = re.compile(r'^(?:(?P<build>.+?)-)?(?P<lane>[A-Z]{2,4})(?P<round>\d+)(?:-(?P<part>[\w.]+))?\.md$')


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    root = args[0] if args else '.'
    found = defaultdict(dict)      # (build, lane) -> round -> (C, M, m, path)
    no_verdict = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in ('.git', 'node_modules', '.build')]
        if 'reviews' not in base.replace('\\', '/').split('/'):
            continue
        for f in files:
            m = NAME.match(f)
            if not m:
                continue
            path = os.path.join(base, f)
            parts = os.path.relpath(base, root).replace('\\', '/').split('/')
            build = m.group('build') or (parts[parts.index('reviews') - 1] if parts.index('reviews') > 0 else '?')
            head = open(path, encoding='utf-8', errors='replace').read(1500)
            v = VERDICT.search(head)
            if not v:
                no_verdict.append(os.path.relpath(path, root))
                continue
            rnd = int(m.group('round'))
            c, mj, mn = int(v.group(1)), int(v.group(2)), int(v.group(3) or 0)
            old = found[(build, m.group('lane'))].get(rnd, (0, 0, 0, ''))
            found[(build, m.group('lane'))][rnd] = (old[0] + c, old[1] + mj, old[2] + mn, path)

    if not found:
        print('No review files with a verdict line found.')
        return 0
    lines = ['| Build | Lane | Rounds | First round C / M / m | Last round C / M | Closed at 0/0? |', '|---|---|---|---|---|---|']
    over = 0
    for (build, lane), rounds in sorted(found.items()):
        first, last = rounds[min(rounds)], rounds[max(rounds)]
        closed = 'yes' if last[0] == 0 and last[1] == 0 else '**no**'
        n = len(rounds)
        over += n > 5
        lines.append(f'| {build} | {lane} | {n}{" ⚠" if n > 5 else ""} | {first[0]} / {first[1]} / {first[2]} | {last[0]} / {last[1]} | {closed} |')
    table = '\n'.join(lines)
    print(table)
    loops = len(found)
    med = sorted(len(r) for r in found.values())[loops // 2]
    print(f'\n{loops} review loops. Median {med} rounds. {over} went past 5 rounds.')
    if no_verdict:
        print(f'{len(no_verdict)} review file(s) have no verdict line in their first lines, e.g. {no_verdict[0]}')
    if '--index' in sys.argv:
        out = os.path.join(root, 'work', 'REVIEWS-INDEX.md') if os.path.isdir(os.path.join(root, 'work')) else os.path.join(root, 'reviews', 'INDEX.md')
        open(out, 'w', encoding='utf-8').write('# Reviews index\n\nGenerated by `metrics.py`. Do not edit by hand.\n\n' + table + '\n')
        print(f'Wrote {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
