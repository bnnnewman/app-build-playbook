#!/usr/bin/env python3
"""Maps every SPEC acceptance-test ID to the tests that check it, and writes TESTS.md.

Generalised from Running-App's RulesEngine/scripts/coverage.py ("289 live IDs, 289 covered, 0 missing").

Conventions (templates/SPEC.md §13):
  - SPEC test tables have rows like  | T001 | input | expected |  or  | TI1a | invariant | property |
  - A removed test stays as a tombstone row whose input starts with "(Removed"
  - Test functions carry the ID(s): test_T001_..., test_T001_T002_..., test_TI1a_...  (any language)

Usage (from the project root):
  python3 coverage.py --spec SPEC.md --tests 'Tests/**/*.swift' [--tests 'more/**/*.py'] [--out TESTS.md]
Exits 1 if any live ID has no test, so it can run in CI.
"""
import argparse, glob, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument('--spec', default='SPEC.md')
ap.add_argument('--start', default=r'^## 13\.', help='regex for the heading that starts the tests section')
ap.add_argument('--end', default=r'^## 14\.', help='regex for the heading after the tests section')
ap.add_argument('--tests', action='append', required=True, help='glob for test files (repeatable)')
ap.add_argument('--out', default='TESTS.md')
args = ap.parse_args()

lines = open(args.spec, encoding='utf-8').read().splitlines()
start = next(i for i, l in enumerate(lines) if re.match(args.start, l))
end = next((i for i, l in enumerate(lines) if i > start and re.match(args.end, l)), len(lines))

ids, order, subsec = {}, [], None
for line in lines[start:end]:
    m = re.match(r'###\s+(.*)', line)
    if m:
        subsec = m.group(1).strip(); continue
    m = re.match(r'\|\s*(TI?\d+[a-z]?)\s*\|\s*(.*?)\s*\|', line)
    if m and subsec:
        ids[m.group(1)] = (subsec, m.group(2)); order.append(m.group(1))

tests = {}
for pattern in args.tests:
    for f in glob.glob(pattern, recursive=True):
        text = open(f, encoding='utf-8', errors='replace').read()
        for m in re.finditer(r'test_((?:TI?\d+[a-z]?_?)+)\w*', text):
            for tid in re.findall(r'TI?\d+[a-z]?', m.group(1)):
                tests.setdefault(tid, set()).add(f'{os.path.relpath(f)}::{m.group(0)}')

removed = {i for i, (_, inp) in ids.items() if inp.startswith('(Removed')}
live = [i for i in order if i not in removed]
missing = [i for i in live if i not in tests]
unknown = sorted(set(tests) - set(ids))

out = ['# Test coverage', '',
       f'Generated by `coverage.py` from `{args.spec}` and the test names. Do not edit by hand.', '',
       f'**{len(live)} live IDs, {len(live) - len(missing)} covered, {len(missing)} missing.** '
       f'Removed in the SPEC: {", ".join(sorted(removed)) or "none"}. '
       f'Test IDs not in the SPEC: {", ".join(unknown) or "none"}.', '']
cur = None
for i in order:
    s, inp = ids[i]
    if s != cur:
        out += ['', f'## {s}', '', '| ID | Input (SPEC) | Test(s) |', '|---|---|---|']; cur = s
    inp = inp.replace('|', '\\|')
    inp = inp if len(inp) <= 90 else inp[:87] + '…'
    t = 'removed' if i in removed else '<br>'.join(f'`{x}`' for x in sorted(tests.get(i, []))) or '**MISSING**'
    out.append(f'| {i} | {inp} | {t} |')
open(args.out, 'w', encoding='utf-8').write('\n'.join(out) + '\n')

print(f'{len(live)} live IDs, {len(live) - len(missing)} covered, {len(missing)} missing'
      + (f': {", ".join(missing)}' if missing else ''), file=sys.stderr)
sys.exit(1 if missing else 0)
