#!/usr/bin/env python3
"""Maps every SPEC test ID to the tests that check it, and writes TESTS.md.

It reads the IDs from the SPEC itself, whatever their prefix (T001, TI1a, RH-T12, A01), so new prefixes are never
invisible to it. It also counts table rows in the tests section whose first cell it could NOT read as an ID, and
fails on those: a coverage figure that silently skips rows is false comfort.

  - A removed test stays as a row whose input starts with "(Removed".
  - Test names carry the ID with '-' written as '_':  test_T001_..., test_T001_T002_..., test_RH_T12_...

Usage (from the project root):
  python3 coverage.py --spec SPEC.md --tests 'Tests/**/*.swift' [--tests 'more/**/*.py'] [--out TESTS.md]
Exits 1 if any live ID has no test or any row couldn't be read, so it can gate a close.
"""
import argparse, glob, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument('--spec', default='SPEC.md')
ap.add_argument('--start', default=r'^## 13\.', help='regex for the heading that starts the tests section')
ap.add_argument('--end', default=r'^## 14\.', help='regex for the heading after the tests section')
ap.add_argument('--tests', action='append', required=True, help='glob for test files (repeatable)')
ap.add_argument('--out', default='TESTS.md')
args = ap.parse_args()

IDCELL = re.compile(r'^[A-Z][A-Za-z]*(?:-[A-Z][A-Za-z]*)*-?\d+[a-z]?$')
lines = open(args.spec, encoding='utf-8').read().splitlines()
start = next(i for i, l in enumerate(lines) if re.match(args.start, l))
end = next((i for i, l in enumerate(lines) if i > start and re.match(args.end, l)), len(lines))

ids, order, subsec, unread = {}, [], None, []
for n, line in enumerate(lines[start:end], start + 1):
    m = re.match(r'###\s+(.*)', line)
    if m:
        subsec = m.group(1).strip(); continue
    if not line.lstrip().startswith('|'):
        continue
    cells = [c.strip() for c in line.strip().strip('|').split('|')]
    first = cells[0].replace('`', '').replace('*', '')
    if not first or re.fullmatch(r':?-{2,}:?', first) or first.lower() in ('id', 'test', 'test id', '#'):
        continue
    if IDCELL.match(first):
        ids[first] = (subsec or '', cells[1] if len(cells) > 1 else ''); order.append(first)
    else:
        unread.append((n, first[:30]))

names = {}
for pattern in args.tests:
    for f in glob.glob(pattern, recursive=True):
        text = open(f, encoding='utf-8', errors='replace').read()
        for name in set(re.findall(r'\btest_\w+', text)):
            names.setdefault(name, os.path.relpath(f))

tests = {}
for i in ids:
    token = re.escape(i.replace('-', '_'))
    pat = re.compile(r'(?:^|_)' + token + r'(?:_|$)')
    hits = sorted(f'{path}::{name}' for name, path in names.items() if pat.search(name[5:]))
    if hits:
        tests[i] = hits

removed = {i for i, (_, inp) in ids.items() if inp.startswith('(Removed')}
live = [i for i in order if i not in removed]
missing = [i for i in live if i not in tests]

out = ['# Test coverage', '',
       f'Generated by `coverage.py` from `{args.spec}` and the test names. Do not edit by hand.', '',
       f'**{len(live)} live IDs, {len(live) - len(missing)} covered, {len(missing)} missing, '
       f'{len(unread)} rows it could not read.** Removed in the SPEC: {", ".join(sorted(removed)) or "none"}.', '']
cur = None
for i in order:
    s, inp = ids[i]
    if s != cur:
        out += ['', f'## {s}', '', '| ID | Input (SPEC) | Test(s) |', '|---|---|---|']; cur = s
    inp = inp.replace('|', '\\|')
    inp = inp if len(inp) <= 90 else inp[:87] + '…'
    t = 'removed' if i in removed else '<br>'.join(f'`{x}`' for x in tests.get(i, [])) or '**MISSING**'
    out.append(f'| {i} | {inp} | {t} |')
open(args.out, 'w', encoding='utf-8').write('\n'.join(out) + '\n')

msg = f'{len(live)} live IDs, {len(live) - len(missing)} covered, {len(missing)} missing'
if missing:
    msg += ': ' + ', '.join(missing[:20])
if unread:
    msg += f'; {len(unread)} rows could not be read as a test ID, e.g. line {unread[0][0]} ("{unread[0][1]}")'
print(msg, file=sys.stderr)
sys.exit(1 if missing or unread else 0)
